#!/usr/bin/env python3
"""Generate src/core/legacy/Cp949Table.inc from Python's built-in cp949 codec.

CP949 (Unified Hangul Code) is the Windows superset of EUC-KR (KS X 1001). The table maps every
double-byte sequence lead 0x81-0xFE / trail 0x41-0xFE to its Unicode code point (0 = undefined).
It is a public character-set standard, not game data. Run from the repository root:

    python3 tools/i18n/gen_cp949_table.py
"""
from pathlib import Path

LEAD_FIRST, LEAD_LAST = 0x81, 0xFE
TRAIL_FIRST, TRAIL_LAST = 0x41, 0xFE


def main() -> int:
    values = []
    for lead in range(LEAD_FIRST, LEAD_LAST + 1):
        for trail in range(TRAIL_FIRST, TRAIL_LAST + 1):
            try:
                text = bytes([lead, trail]).decode("cp949")
                values.append(ord(text) if len(text) == 1 else 0)
            except UnicodeDecodeError:
                values.append(0)
    lines = ["// Generated by tools/i18n/gen_cp949_table.py - do not edit.",
             "// CP949 double-byte -> Unicode, index = (lead - 0x81) * 190 + (trail - 0x41), 0 = undefined."]
    for i in range(0, len(values), 16):
        lines.append(",".join(f"0x{v:04X}" for v in values[i:i + 16]) + ",")
    out = Path("src/core/legacy/Cp949Table.inc")
    out.write_text("\n".join(lines) + "\n", encoding="ascii")
    print(f"wrote {out} ({len(values)} entries, {sum(1 for v in values if v)} defined)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
