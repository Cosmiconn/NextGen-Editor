def output_dir(project_root: Path) -> Path:
    return project_root.resolve() / "Client" / "resmap" / "field" / MAP_ID


def write_walk_grid(source_client: Path, target: Path, placements: list[base.Placement]):
    source = source_client / "resmap" / "field" / "Rou" / "Rou.shbd"
    grid = base.WalkGridTemplate(source.read_bytes())
    grid.set_world_rect(6750, 450, 11850, 5300, False)
    for obj in placements:
        if obj.collision_x > 0 and obj.collision_y > 0:
            grid.set_world_rect(obj.x-obj.collision_x, obj.y-obj.collision_y,
                                obj.x+obj.collision_x, obj.y+obj.collision_y, True)
    target.write_bytes(grid.to_bytes())
    return {"rows":grid.rows,"cols":grid.cols,"cell_size":grid.cell_size,
            "words_per_row":grid.words_per_row}


def sha256(path: Path) -> str:
    h=hashlib.sha256(); h.update(path.read_bytes()); return h.hexdigest()


def write_layout(path: Path, placements: list[base.Placement], *, terrain=None, walk=None):
    data = {
        "map_id": MAP_ID,
        "title": MAP_TITLE,
        "level_range": [75,125],
        "visual_target": "tiered coastal white-stone/royal-blue fantasy citadel",
        "render_truth": "placements reference the same generated NIFs used by the renderer evidence",
        "districts": DISTRICTS,
        "npc_anchors": NPC_ANCHORS,
        "portal_anchors": PORTAL_ANCHORS,
        "safe_spawn": [9300,2350,520],
        "terrain_template": terrain,
        "walk_grid": walk,
        "placements": [asdict(x) for x in placements],
        "dependencies": sorted({x.model for x in placements}),
    }
    path.write_text(json.dumps(data, indent=2, ensure_ascii=False)+"\n", encoding="utf-8")


def generate_scene(output: Path) -> Path:
    if output.exists(): shutil.rmtree(output)
    output.mkdir(parents=True)
    asset_dir = output / "assets"
    assets.generate(asset_dir)
    placements = build_reference_city()
    base.write_shmd(output / f"{MAP_ID}.shmd", placements)
    write_layout(output / f"{MAP_ID}.layout.json", placements)
    print(f"Scene: {len(placements)} placements / {len(assets.ALL_ASSETS)} generated NIF types")
    return output


def normalize_client(path: Path) -> Path:
    path = path.resolve()
    if (path / "Client" / "resmap").is_dir(): path = path / "Client"
    return path


def generate_map(source_client: Path, project_root: Path, force: bool) -> Path:
    client = normalize_client(source_client)
    source_field = client / "resmap" / "field" / "Rou"
    required = [source_field/"Rou.HTD", source_field/"Rou.HTDG", source_field/"Rou.shbd"]
    missing=[str(x) for x in required if not x.is_file()]
    if missing: raise SystemExit("Missing Rou terrain templates:\n  - " + "\n  - ".join(missing))
    out=output_dir(project_root)
    if out.exists():
        if not force: raise SystemExit(f"Output exists: {out}; use --force")
        shutil.rmtree(out)
    out.mkdir(parents=True)
    placements=build_reference_city()
    assets.generate(out/"assets")
    shutil.copyfile(source_field/"Rou.HTD", out/f"{MAP_ID}.HTD")
    shutil.copyfile(source_field/"Rou.HTDG", out/f"{MAP_ID}.HTDG")
    base.write_ini(out/f"{MAP_ID}.ini")
    base.write_shmd(out/f"{MAP_ID}.shmd", placements)
    walk=write_walk_grid(client,out/f"{MAP_ID}.shbd",placements)
    terrain={"map":"Rou","htd_sha256":sha256(source_field/"Rou.HTD"),
             "htdg_sha256":sha256(source_field/"Rou.HTDG"),"world_size":[12800,12800]}
    write_layout(out/f"{MAP_ID}.layout.json",placements,terrain=terrain,walk=walk)
    (out/"README-Aurelia75-v2.txt").write_text(
        f"{MAP_TITLE}\nObjects: {len(placements)}\nGenerated NIF types: {len(assets.ALL_ASSETS)}\n"
        "Open Aurelia75.ini in NextGen-Editor. NPC/portal IDs remain intentionally unbound.\n",
        encoding="utf-8")
    print(f"Generated real map: {out}\nObjects: {len(placements)}")
    return out


def main() -> int:
    ap=argparse.ArgumentParser()
    ap.add_argument("--scene-only",action="store_true")
    ap.add_argument("--output",type=Path,default=Path("build/aurelia-reference-scene"))
    ap.add_argument("--source-client",type=Path)
    ap.add_argument("--project-root",type=Path)
    ap.add_argument("--force",action="store_true")
    args=ap.parse_args()
    if args.scene_only:
        generate_scene(args.output); return 0
    if not args.source_client or not args.project_root:
        ap.error("--source-client and --project-root are required unless --scene-only is used")
    generate_map(args.source_client,args.project_root,args.force)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
