def A(out, model, x, y, z, yaw=0.0, scale=1.0, collision=None, district="", note=""):
    base.add(out, model, x, y, elevation=z, yaw=yaw, scale=scale,
             collision=collision, district=district, note=note)


def line(out, model, x0, y0, x1, y1, z, spacing, *, yaw=None, scale=1.0,
         collision=None, district="walls", skip=()):
    dx, dy = x1-x0, y1-y0
    length = math.hypot(dx, dy)
    count = max(1, int(round(length / spacing)))
    angle = math.degrees(math.atan2(dy, dx))
    model_yaw = angle if yaw is None else yaw
    for i in range(count + 1):
        t = i / count
        x, y = x0 + dx*t, y0 + dy*t
        if any(math.hypot(x-sx, y-sy) < radius for sx, sy, radius in skip):
            continue
        A(out, model, x, y, z, model_yaw, scale, collision, district)


def ring_positions(cx, cy, rx, ry, count, phase=0.0):
    for i in range(count):
        a = 2*math.pi*i/count + phase
        yield cx + math.cos(a)*rx, cy + math.sin(a)*ry, math.degrees(a) + 90


def build_reference_city() -> list[base.Placement]:
    p: list[base.Placement] = []

    # Sea/horizon geometry used both by the actual map and deterministic evidence renderer.
    A(p, WATER, 9300, 250, 385, scale=1.35, district="harbor", note="south sea basin")

    # ------------------------------------------------------------------
    # Outer fortified city ring: broad white walls, blue-roof towers and four gates.
    # ------------------------------------------------------------------
    south_y, north_y, west_x, east_x = 1850, 4950, 7350, 11250
    wall_z = 500
    line(p, WALL, west_x, south_y, east_x, south_y, wall_z, 575,
         collision=(285, 70), skip=((9300, south_y, 470),))
    line(p, WALL, west_x, north_y, east_x, north_y, 790, 575,
         collision=(285, 70), skip=((9300, north_y, 470),))
    line(p, WALL, west_x, south_y, west_x, north_y, wall_z, 575, yaw=90,
         collision=(70, 285), skip=((west_x, 3300, 470),))
    line(p, WALL, east_x, south_y, east_x, north_y, wall_z, 575, yaw=90,
         collision=(70, 285), skip=((east_x, 3300, 470),))
    for x, y, z in [
        (west_x, south_y, 490), (east_x, south_y, 490),
        (west_x, north_y, 780), (east_x, north_y, 780),
        (8050, south_y, 490), (10550, south_y, 490),
        (west_x, 2650, 520), (west_x, 4100, 690),
        (east_x, 2650, 520), (east_x, 4100, 690),
        (8050, north_y, 780), (10550, north_y, 780),
    ]:
        A(p, TOWER, x, y, z, collision=(175,175), district="walls")
    A(p, GATE, 9300, south_y, 495, 0, 1.05, (520,180), "westtor", "grand harbor gate")
    A(p, GATE, 9300, north_y, 785, 180, 1.05, (520,180), "morgenwacht", "north citadel gate")
    A(p, GATE, west_x, 3300, 575, 90, 0.92, (180,520), "westtor")
    A(p, GATE, east_x, 3300, 575, 90, 0.92, (180,520), "veteranen")

    # East and west monumental access bridges hanging over the cliff line.
    A(p, BRIDGE, 6920, 3300, 470, 90, 1.0, (690,240), "westtor")
    A(p, BRIDGE, 11680, 3300, 470, 90, 1.0, (690,240), "veteranen")

    # ------------------------------------------------------------------
    # Harbor: lighthouse, piers, warehouses, seafront shops and cargo.
    # ------------------------------------------------------------------
    A(p, LIGHTHOUSE, 7600, 850, 390, 0, 1.18, (260,260), "harbor", "western beacon")
    A(p, LIGHTHOUSE, 11000, 1050, 400, 0, 0.92, (240,240), "harbor", "eastern beacon")
    for x in (8200, 8750, 9300, 9850, 10400):
        A(p, PIER, x, 1050, 410, 0, 0.82, (180,600), "harbor")
        A(p, STORE, x, 1650, 485, 180, 0.72, (260,190), "harbor")
        A(p, CRATES, x-170, 1425, 485, (x//50)%180, 0.8, (75,75), "harbor")
        A(p, BARREL, x+165, 1435, 485, 0, 0.85, (40,40), "harbor")

    # ------------------------------------------------------------------
    # Lower city / Kronmarkt: dense radial market around the fountain.
    # ------------------------------------------------------------------
    A(p, TERRACE, 9300, 2920, 500, 0, 1.24, (1000,760), "market", "grand civic terrace")
    A(p, FOUNTAIN, 9300, 2850, 655, 0, 1.10, (470,470), "market", "Aurelia sun fountain")
    for x, y, yaw in ring_positions(9300, 2850, 760, 570, 18, phase=0.10):
        A(p, STALL, x, y, 635, yaw+90, 0.52, (115,70), "market")
    for x, y, yaw in ring_positions(9300, 2850, 1080, 820, 14, phase=0.02):
        A(p, HOUSE_B if int(x+y)%2 else HOUSE_A, x, y, 515, yaw+90, 0.72,
          (190,155), "market")
    for x, y, yaw in ring_positions(9300, 2850, 620, 470, 12, phase=0.22):
        A(p, LAMP, x, y, 640, 0, 0.72, (22,22), "market")
    for x, y, yaw in ring_positions(9300, 2850, 1180, 930, 14, phase=0.18):
        A(p, TREE, x, y, 510, 0, 0.48, (90,90), "market")

    # Main stores define the civic crossroads.
    for x, y, yaw in [(8200,2780,90),(10400,2780,-90),(8400,3500,120),(10200,3500,-120)]:
        A(p, STORE, x, y, 535 if y<3200 else 585, yaw, 0.82, (320,220), "market")

    # ------------------------------------------------------------------
    # Mid terrace / Runenwerk and veteran quarter.
    # ------------------------------------------------------------------
    A(p, TERRACE, 8500, 3800, 590, 0, 1.02, (900,660), "runenwerk")
    A(p, TERRACE, 10100, 3800, 590, 0, 1.02, (900,660), "veteranen")
    A(p, COLONNADE, 8500, 3960, 745, 0, 0.90, (560,180), "runenwerk")
    A(p, COLONNADE, 10100, 3960, 745, 0, 0.90, (560,180), "veteranen")
    for base_x, district in ((8200,"runenwerk"),(9950,"veteranen")):
        for row in range(2):
            for col in range(4):
                x = base_x + col*310
                y = 3400 + row*430
                A(p, HOUSE_B if (row+col)%2 else HOUSE_A, x, y, 580+row*55, 180, 0.62,
                  (165,135), district)
    for x in (7900,8150,10450,10700):
        for y in (3450,3900,4300):
            A(p, TREE, x, y, 590+(y-3450)*0.18, 0, 0.42, (80,80), "gardens")
            A(p, PLANTER, x+90, y+40, 605+(y-3450)*0.18, 90, 0.55, (75,35), "gardens")

    # ------------------------------------------------------------------
    # Monumental ascent. The broad staircase creates the reference-image vertical hierarchy.
    # ------------------------------------------------------------------
    A(p, STAIRS, 9300, 3820, 625, 0, 1.12, (460,900), "morgenwacht", "grand ascent")
    for x in (8750, 9850):
        A(p, COLONNADE, x, 4240, 770, 90 if x<9300 else -90, 0.78, (420,150), "morgenwacht")
        for y in (4060,4400):
            A(p, TREE, x + (-220 if x<9300 else 220), y, 760, 0, 0.46, (85,85), "gardens")

    # ------------------------------------------------------------------
    # Upper citadel: second terrace and dominant cathedral/palace silhouette.
    # ------------------------------------------------------------------
    A(p, TERRACE, 9300, 4620, 820, 0, 1.34, (1100,780), "morgenwacht", "cathedral terrace")
    A(p, CATHEDRAL, 9300, 4680, 970, 0, 1.12, (800,620), "morgenwacht", "Bastion of the Morning Watch")
    for x in (8250, 10350):
        A(p, TOWER, x, 4620, 815, 0, 0.82, (150,150), "morgenwacht")
        A(p, COLONNADE, x, 4490, 805, 0, 0.72, (430,150), "morgenwacht")
    for x, y, yaw in ring_positions(9300, 4590, 1320, 520, 18, phase=0.12):
        A(p, TREE, x, y, 815, yaw, 0.43, (78,78), "gardens")

    # ------------------------------------------------------------------
    # Residential infill: intentionally irregular to avoid a sterile grid.
    # ------------------------------------------------------------------
    residential = [
        (7700,2200,0),(8000,2180,8),(8320,2200,-8),(10700,2200,5),(10380,2180,-8),(10050,2200,6),
        (7700,2550,12),(8000,2520,-4),(10680,2530,-8),(10360,2520,5),
        (7700,3000,4),(7900,3200,-12),(10880,3000,-4),(10680,3200,10),
        (7800,3650,16),(10800,3650,-16),(7850,4100,10),(10750,4100,-10),
    ]
    for i,(x,y,yaw) in enumerate(residential):
        z = 500 + max(0,y-2600)*0.10
        A(p, HOUSE_B if i%3 else HOUSE_A, x, y, z, yaw, 0.68, (175,145), "residential")
        if i % 2 == 0:
            A(p, LAMP, x+180, y-80, z+5, 0, 0.62, (18,18), "residential")

    # Flower-lined processional route from harbor gate to cathedral.
    for y in range(2050, 4501, 250):
        if 2600 <= y <= 3200:
            continue
        z = 510 + max(0, y-3200)*0.13
        for x in (9030, 9570):
            A(p, PLANTER, x, y, z, 90, 0.52, (70,34), "processional")
            A(p, LAMP, x + (-70 if x<9300 else 70), y, z, 0, 0.58, (18,18), "processional")

    # Benches and trees around civic spaces.
    for x,y,yaw in [(8750,2700,90),(9850,2700,-90),(8750,3050,90),(9850,3050,-90),
                    (8650,3320,0),(9950,3320,180),(8700,4450,0),(9900,4450,180)]:
        z = 520 + max(0,y-3200)*0.13
        A(p, BENCH, x,y,z,yaw,0.58,(95,35),"gardens")

    return p


